# Function to demonstrate resonance-based pattern emergence
sub simulate_resonance_emergence {
    my $pattern_space = shift;
    my $iterations = shift || 100;

    say "Initializing pattern space with random values...";
    my @space = init_pattern_space($pattern_space);

    say "Running resonance simulation for $iterations iterations...";
    my $resonant_score = 0;
    my $momentum = 0;
    my $previous_score = 0;

    for my $i (1..$iterations) {
        # Apply resonance rules to current pattern space
        @space = apply_resonance_rules(\@space);

        # Measure harmonic integrity
        my $current_score = measure_harmonic_integrity(\@space);

        # Calculate momentum (improvement rate)
        if ($i > 1) {
            my $improvement = $current_score - $previous_score;
            $momentum = ($momentum * 0.9) + ($improvement * 0.1); # Weighted average
        }

        $previous_score = $current_score;
        $resonant_score = $current_score;

        # Log every 10 iterations
        if ($i % 10 == 0) {
            say "Iteration $i: Harmonic integrity = $current_score, Momentum = $momentum";
        }
    }

    say "\nFinal harmonic integrity: $resonant_score";
    say "Final optimization momentum: $momentum";

    return ($resonant_score, $momentum);
}

